class CarEntity {
  final int id;
  final String name;
  final String brand;
  final double price;
  final double rating;
  final int reviews;
  final String transmission;
  final String image;

  const CarEntity({
    required this.id,
    required this.name,
    required this.brand,
    required this.price,
    required this.rating,
    required this.reviews,
    required this.transmission,
    required this.image,
  });
}
